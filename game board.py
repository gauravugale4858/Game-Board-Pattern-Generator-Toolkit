def display_board(board):
    symbols = {0: "", 1: "X", 2: "O"}

    fig, ax = plt.subplots(figsize=(4, 4))
    ax.imshow(np.zeros((3, 3)), cmap="Pastel2", vmin=0, vmax=1)

    ax.set_xticks(np.arange(-0.5, 3, 1))
    ax.set_yticks(np.arange(-0.5, 3, 1))
    ax.grid(color="black", linewidth=2)

    ax.set_xticklabels([])
    ax.set_yticklabels([])

    for row in range(3):
        for col in range(3):
            ax.text(
                col, row, symbols[board[row, col]],
                ha="center", va="center",
                fontsize=35, fontweight="bold"
            )

    ax.set_title("Tic-Tac-Toe Board")
    plt.tight_layout()
    plt.show()


