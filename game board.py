def play_game():
    board = np.zeros((3, 3), dtype=int)
    player = 1

    while True:
        display_board(board)

        try:
            row = int(input(f"Player {'X' if player == 1 else 'O'}, enter row (0-2): "))
            col = int(input("Enter column (0-2): "))

            if row not in range(3) or col not in range(3):
                print("Enter numbers from 0 to 2.")
                continue

            if board[row, col] != 0:
                print("That position is already occupied.")
                continue

        except ValueError:
            print("Please enter valid integers.")
            continue

        board[row, col] = player

        winner = check_winner(board)

        if winner != 0:
            display_board(board)
            print(f"Player {'X' if winner == 1 else 'O'} wins!")
            break

        if np.all(board != 0):
            display_board(board)
            print("It's a draw!")
            break

        player = 3 - player


play_game()